# -*- coding: utf-8 -*-
"""按书名关键词把 books.json 的 category 字段自动归入新版分类体系。
新版分类（取自用户截图）：
  全部 / 都市激情 / 校园之恋 / 人妻熟女 / 家庭乱伦 / 经验故事
  / 真实体验 / 猎奇另类 / 短篇笑话 / 古典武侠 / 91博客
规则：按优先级关键词匹配，未命中归入「都市激情」（最宽泛的都市/成人综合类）。
"""
import json, re

SRC = 'books.json'

# 命中即归类的有序规则（先匹配先赢）
RULES = [
    ('古典武侠', ['武侠','江湖','仙侠','修真','玄幻','古代','古风','穿越','宫斗','后宫','唐朝','宋朝','明朝','清朝','三国','王爷','公主','妃','王朝','妖','神仙','神话','异界','门派','剑侠','侠','宫廷','皇帝','皇后']),
    ('校园之恋', ['校园','校花','学妹','学弟','同学','大学','高中','学院','学生','老师','教室','青春','同桌','校草','萝莉','少年','少女']),
    ('短篇笑话', ['笑话','段子','幽默','搞笑','爆笑','趣事','短篇']),
    ('人妻熟女', ['人妻','熟女','少妇','妻子','老婆','已婚','寡妇','嫂子','阿姨','御姐','美妇','人妇','主妇','邻家','丰满','风韵']),
    ('家庭乱伦', ['乱伦','父女','母子','母女','兄妹','姐弟','叔侄','父子','家人','亲戚','禁忌','一家亲','长辈']),
    ('猎奇另类', ['猎奇','另类','变性','人兽','癖好','调教','强制','迷奸','凌辱','群交','重口','催眠','春药','迷药','奇遇','异能','特殊']),
    ('91博客',   ['91','博客','日志','微博','贴吧','日记本']),
    ('经验故事', ['经验','技巧','心得','攻略','教程','招数','秘籍','方法']),
    ('真实体验', ['真实','实录','自述','经历','日记','口述','亲身','纪实','我的','那夜','那次','第一次','往事','回忆','随笔']),
    ('都市激情', ['都市','城市','职场','总裁','豪门','医生','护士','白领','老板','情人','出轨','一夜','邻居','秘书','空姐','按摩','洗浴','会所','酒店','包养','小三','婚姻','恋爱','爱情','约','艳','激情','诱惑','欲望','性','床','蜜月','偷']),
]

# 兜底分类
DEFAULT = '都市激情'

def classify(title):
    t = (title or '')
    for cat, kws in RULES:
        for kw in kws:
            if kw in t:
                return cat
    return DEFAULT

def main():
    data = json.load(open(SRC, encoding='utf-8'))
    before = {}
    for b in data:
        before[b.get('category','')] = before.get(b.get('category',''),0)+1
    for b in data:
        b['category'] = classify(b.get('title',''))
    # 统计
    after = {}
    for b in data:
        after[b['category']] = after.get(b['category'],0)+1
    json.dump(data, open(SRC,'w',encoding='utf-8'), ensure_ascii=False, separators=(',',':'))
    print('总数:', len(data))
    print('--- 旧分类 Top ---')
    for k,v in sorted(before.items(), key=lambda x:-x[1])[:12]:
        print(f'  {k or "(空)"}: {v}')
    print('--- 新分类分布 ---')
    order = ['都市激情','校园之恋','人妻熟女','家庭乱伦','经验故事','真实体验','猎奇另类','短篇笑话','古典武侠','91博客']
    for k in order:
        print(f'  {k}: {after.get(k,0)}')
    other = {k:v for k,v in after.items() if k not in order}
    for k,v in other.items():
        print(f'  [其他]{k}: {v}')

if __name__ == '__main__':
    main()
